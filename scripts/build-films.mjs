#!/usr/bin/env node
// Builds the films pages from films/films.json:
//   films/index.html          every film in a grid
//   films/<slug>/index.html   one page per film
//
// Run it after you edit films/films.json (upload-film.mjs runs it for you):
//   node scripts/build-films.mjs
// Add --check to only report whether the committed pages are out of date.
//
// Plain Node, no packages needed.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const FILMS_DIR = join(ROOT, 'films');
export const CONFIG_PATH = join(FILMS_DIR, 'films.json');

const MARK = '<!-- Generated by scripts/build-films.mjs from films/films.json. Edit that file and rebuild, not this page. -->';
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DURATION = /^(?:(\d+):)?(\d{1,2}):(\d{2})$/;
// The optional credit lists a film can carry, in the order the pages show them.
const CREDITS = [['models', 'Models', '["Opus 5.5", "Lyria 3"]'], ['tools', 'Tools', '["Blender", "Claude Desktop Projects"]']];

// ---------- Config ----------

export function readConfig(path = CONFIG_PATH) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

export function validate(config) {
  const errors = [];
  const warn = [];
  if (!config || typeof config !== 'object') return { errors: ['films.json must hold an object'], warn };
  if (!isUrl(config.siteUrl)) errors.push('siteUrl must be the site\'s full address, like https://emsav-six.vercel.app');
  if (!Array.isArray(config.films)) errors.push('films must be a list');
  const seen = new Set();
  (config.films || []).forEach((f, i) => {
    const at = `films[${i}]${f && f.slug ? ` (${f.slug})` : ''}`;
    if (!f || typeof f !== 'object') { errors.push(`${at} must be an object`); return; }
    if (!nonEmpty(f.title)) errors.push(`${at}: title is missing`);
    if (!nonEmpty(f.slug) || !SLUG.test(f.slug)) errors.push(`${at}: slug must be lowercase words joined by dashes, like "paper-moon"`);
    else if (seen.has(f.slug)) errors.push(`${at}: slug "${f.slug}" is used twice`);
    else seen.add(f.slug);
    if (!isUrl(f.video)) errors.push(`${at}: video must be the film's full Blob URL (https://…/film.mp4)`);
    else if (!f.video.startsWith('https://')) warn.push(`${at}: video is not on https, which only makes sense for local testing`);
    checkImage(f.poster, `${at}: poster`, errors, true);
    checkImage(f.ogImage, `${at}: ogImage`, errors, false);
    if (!nonEmpty(f.duration) || !DURATION.test(f.duration)) errors.push(`${at}: duration must look like 2:41 or 1:02:41`);
    if (f.description != null && typeof f.description !== 'string') errors.push(`${at}: description must be text`);
    if (f.date != null && !/^\d{4}-\d{2}-\d{2}$/.test(f.date)) errors.push(`${at}: date must look like 2026-11-01`);
    for (const [key, , example] of CREDITS) {
      if (f[key] != null && (!Array.isArray(f[key]) || !f[key].every(nonEmpty))) errors.push(`${at}: ${key} must be a list of names, like ${example}`);
    }
    if (f.captions != null) {
      if (!Array.isArray(f.captions)) errors.push(`${at}: captions must be a list`);
      else f.captions.forEach((c, j) => {
        const cat = `${at}: captions[${j}]`;
        // Captions stay on the site itself: a caption file from another origin needs CORS on the video too.
        if (!c || !nonEmpty(c.src) || !c.src.startsWith('/')) errors.push(`${cat}: src must be a path on this site, like /films/${f.slug || 'slug'}/captions.en.vtt`);
        else if (!existsSync(join(ROOT, c.src))) errors.push(`${cat}: ${c.src} is not in the repo`);
        if (!c || !nonEmpty(c.srclang)) errors.push(`${cat}: srclang is missing (like "en")`);
        if (!c || !nonEmpty(c.label)) errors.push(`${cat}: label is missing (like "English")`);
      });
    }
  });
  return { errors, warn };
}

function checkImage(value, label, errors, required) {
  if (value == null && !required) return;
  if (isUrl(value)) return;
  if (nonEmpty(value) && value.startsWith('/')) {
    if (!existsSync(join(ROOT, value))) errors.push(`${label}: ${value} is not in the repo`);
    return;
  }
  errors.push(`${label} must be a full URL or a path on this site starting with /`);
}

function nonEmpty(v) { return typeof v === 'string' && v.trim() !== ''; }
function isUrl(v) { return typeof v === 'string' && /^https?:\/\/[^\s]+$/.test(v); }

// ---------- Small helpers ----------

export function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

export function durationSeconds(d) {
  const m = DURATION.exec(d);
  return (+(m[1] || 0)) * 3600 + (+m[2]) * 60 + (+m[3]);
}

export function formatDuration(seconds) {
  const s = Math.round(seconds);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const pad = (n) => String(n).padStart(2, '0');
  return h ? `${h}:${pad(m)}:${pad(s % 60)}` : `${m}:${pad(s % 60)}`;
}

function isoDuration(d) {
  const s = durationSeconds(d);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  return `PT${h ? h + 'H' : ''}${m ? m + 'M' : ''}${s % 60}S`;
}

function absolute(config, url) {
  return isUrl(url) ? url : new URL(url, config.siteUrl).href;
}

function filmPath(film) { return `/films/${film.slug}/`; }

function describe(film) {
  return film.description || `${film.title}, a motion graphics film by emSav. ${film.duration} long.`;
}

// The logo is copied from index.html so the films pages always match the home page.
function brand() {
  const html = readFileSync(join(ROOT, 'index.html'), 'utf8');
  const m = /<a class="brand"[\s\S]*?<\/a>/.exec(html);
  if (!m) throw new Error('Could not find the logo (<a class="brand">) in index.html');
  return m[0].replace('href="#top"', 'href="/"');
}

// ---------- The player ----------

// The reusable video player. Without JavaScript it is a plain <video> with native controls.
// film-player.js hides the native controls until the first play, shows the big play button,
// and makes sure only one film plays at a time.
export function player(film) {
  const tracks = (film.captions || []).map((c) =>
    `\n    <track kind="captions" src="${esc(c.src)}" srclang="${esc(c.srclang)}" label="${esc(c.label)}"${c.default ? ' default' : ''}>`
  ).join('');
  return `<div class="film-player" data-film="${esc(film.slug)}">
  <video class="film-video" controls playsinline preload="none" poster="${esc(film.poster)}" aria-label="${esc(film.title)}">
    <source src="${esc(film.video)}" type="video/mp4">${tracks}
    <p class="film-fallback">This browser can't play the film here. <a href="${esc(film.video)}">Download the MP4</a> instead.</p>
  </video>
  <button class="film-play" type="button" aria-label="Play ${esc(film.title)}" hidden>
    <span class="film-play-icon" aria-hidden="true"><svg viewBox="0 0 24 24" focusable="false"><path d="M8 5.6v12.8a.8.8 0 0 0 1.2.7l10.1-6.4a.8.8 0 0 0 0-1.4L9.2 4.9a.8.8 0 0 0-1.2.7z"></path></svg></span>
  </button>
  <p class="film-error" role="status"></p>
</div>`;
}

// What a film was made with: each credit list as a label and a row of tags.
// Returns '' when the film has none, so the page leaves the block out.
export function credits(film, className = 'film-credits') {
  const rows = CREDITS.filter(([key]) => Array.isArray(film[key]) && film[key].length).map(([key, label]) => `
  <div class="film-credit">
    <dt>${label}</dt>
    <dd><ul class="film-tags" role="list">${film[key].map((name) => `<li>${esc(name)}</li>`).join('')}</ul></dd>
  </div>`).join('');
  return rows ? `<dl class="${className}">${rows}
</dl>` : '';
}

// ---------- Page parts ----------

function head(config, { title, description, path, image, imageAlt, film }) {
  const url = absolute(config, path);
  const lines = [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${esc(title)}</title>`,
    `<meta name="description" content="${esc(description)}">`,
    '<meta name="theme-color" content="#120d09">',
    `<link rel="canonical" href="${esc(url)}">`,
    '<meta property="og:site_name" content="emSav">',
    `<meta property="og:type" content="${film ? 'video.other' : 'website'}">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(description)}">`,
    `<meta property="og:url" content="${esc(url)}">`,
  ];
  if (image) {
    lines.push(`<meta property="og:image" content="${esc(absolute(config, image))}">`);
    if (imageAlt) lines.push(`<meta property="og:image:alt" content="${esc(imageAlt)}">`);
  }
  if (film) lines.push(`<meta property="video:duration" content="${durationSeconds(film.duration)}">`);
  lines.push(
    `<meta name="twitter:card" content="${image ? 'summary_large_image' : 'summary'}">`,
    '<link rel="icon" href="/favicon.svg" type="image/svg+xml">',
    '<link rel="preconnect" href="https://fonts.googleapis.com">',
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Schibsted+Grotesk:wght@400;500;600;700&amp;display=swap">',
    '<link rel="stylesheet" href="/styles.css">',
    '<link rel="stylesheet" href="/film-player.css">',
    '<script src="/main.js" defer></script>',
    '<script src="/film-player.js" defer></script>',
  );
  if (film) lines.push(`<script type="application/ld+json">${jsonLd(config, film)}</script>`);
  lines.push('</head>');
  return lines.join('\n');
}

function jsonLd(config, film) {
  const data = {
    '@context': 'https://schema.org',
    '@type': 'VideoObject',
    name: film.title,
    description: describe(film),
    thumbnailUrl: [absolute(config, film.poster)],
    contentUrl: film.video,
    embedUrl: absolute(config, filmPath(film)),
    duration: isoDuration(film.duration),
  };
  if (film.date) data.uploadDate = film.date;
  return JSON.stringify(data).replace(/</g, '\\u003c');
}

function header(current) {
  const link = (href, label, here) => `<a href="${href}"${here ? ' aria-current="page"' : ''}>${label}</a>`;
  return `  <header class="site-header films-header">
    <nav class="site-nav" aria-label="Main">
      ${brand()}
      <div class="nav-links">
        ${link('/#design', 'Design')}
        ${link('/#work', 'Build')}
        ${link('/films/', 'Films', current === 'films')}
        ${link('/#about', 'About')}
      </div>
    </nav>
    <a class="booking" href="/#booking"><span class="booking-dot" aria-hidden="true"></span>Booking</a>
  </header>`;
}

const arrowLeft = '<svg aria-hidden="true" width="16" height="16" viewBox="0 0 24 24"><path d="M19 12H5M11 18l-6-6 6-6"></path></svg>';

// ---------- Pages ----------

export function indexPage(config) {
  const films = config.films;
  const first = films[0];
  const heading = config.heading || 'Films';
  const intro = config.intro || '';
  const count = films.length ? ` · ${String(films.length).padStart(2, '0')}` : '';
  const delays = [0, 90, 180];
  const cards = films.map((f, i) => {
    const made = credits(f, 'film-credits film-credits-compact');
    return `
      <li class="film-card reveal" style="--delay: ${delays[i % 3]}ms">
        ${player(f).replace(/\n/g, '\n        ')}
        <div class="film-card-body">
          <h2 class="film-card-title"><a href="${filmPath(f)}">${esc(f.title)}</a></h2>
          <p class="film-card-meta"><time datetime="${isoDuration(f.duration)}">${esc(f.duration)}</time></p>${f.description ? `
          <p class="film-card-desc">${esc(f.description)}</p>` : ''}${made ? `
          ${made.replace(/\n/g, '\n          ')}` : ''}
        </div>
      </li>`;
  }).join('\n');
  const body = films.length
    ? `<ul class="film-grid" role="list">${cards}
    </ul>`
    : '<p class="films-empty">The first film is on its way.</p>';

  return `${head(config, {
    title: `${heading.replace(/[.!]$/, '')} — emSav`,
    description: intro || 'Motion graphics films by emSav.',
    path: '/films/',
    image: first && (first.ogImage || first.poster),
    imageAlt: first && `A frame from ${first.title}`,
  })}
<body class="films-body">
${MARK}
${header('films')}

<main id="top" class="films-main">

<section class="section" aria-labelledby="films-title">
  <div class="section-inner">

    <div class="section-head reveal">
      <div class="section-title-group">
        <p class="eyebrow">Films${count}</p>
        <h1 id="films-title">${esc(heading)}</h1>
      </div>${intro ? `
      <p class="section-lede">${esc(intro)}</p>` : ''}
    </div>

    ${body}

  </div>
</section>

</main>
</body>
</html>
`;
}

export function filmPage(config, film) {
  const others = config.films.filter((f) => f !== film);
  const made = credits(film);
  const more = others.length ? `

<section class="section film-more-section" aria-labelledby="more-title">
  <div class="section-inner">
    <h2 id="more-title" class="film-more-title">More films</h2>
    <ul class="film-more" role="list">${others.map((f) => `
      <li>
        <a href="${filmPath(f)}">
          <img src="${esc(f.poster)}" alt="" width="1920" height="1080" loading="lazy" decoding="async">
          <span class="film-more-name">${esc(f.title)}</span>
          <span class="film-more-time"><time datetime="${isoDuration(f.duration)}">${esc(f.duration)}</time></span>
        </a>
      </li>`).join('')}
    </ul>
  </div>
</section>` : '';

  return `${head(config, {
    title: `${film.title} — emSav films`,
    description: describe(film),
    path: filmPath(film),
    image: film.ogImage || film.poster,
    imageAlt: film.ogImage ? `A contact sheet of frames from ${film.title}` : `A frame from ${film.title}`,
    film,
  })}
<body class="films-body">
${MARK}
${header()}

<main id="top" class="films-main">

<article class="section film-detail" aria-labelledby="film-title">
  <div class="section-inner">

    <p class="film-back"><a href="/films/">${arrowLeft}All films</a></p>

    ${player(film).replace(/\n/g, '\n    ')}

    <div class="film-info">
      <div class="section-title-group">
        <p class="eyebrow">Film · <time datetime="${isoDuration(film.duration)}">${esc(film.duration)}</time></p>
        <h1 id="film-title">${esc(film.title)}</h1>
      </div>${film.description ? `
      <p class="section-lede">${esc(film.description)}</p>` : ''}
    </div>${made ? `

    ${made.replace(/\n/g, '\n    ')}` : ''}

  </div>
</article>${more}

</main>
</body>
</html>
`;
}

// ---------- Build ----------

// Returns the pages to write as { path: html }, plus the generated pages that no film owns any more.
export function render(config) {
  const pages = { [join(FILMS_DIR, 'index.html')]: indexPage(config) };
  for (const film of config.films) pages[join(FILMS_DIR, film.slug, 'index.html')] = filmPage(config, film);
  const stale = [];
  for (const entry of readdirSync(FILMS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const page = join(FILMS_DIR, entry.name, 'index.html');
    if (!pages[page] && existsSync(page) && readFileSync(page, 'utf8').includes(MARK)) stale.push(page);
  }
  return { pages, stale };
}

export function build({ check = false, config = readConfig(), log = console.log } = {}) {
  const { errors, warn } = validate(config);
  warn.forEach((w) => log(`warning: ${w}`));
  if (errors.length) {
    const e = new Error(`films/films.json has problems:\n  - ${errors.join('\n  - ')}`);
    e.code = 'FILMS_CONFIG';
    throw e;
  }
  const { pages, stale } = render(config);
  const changed = Object.entries(pages).filter(([p, html]) => !existsSync(p) || readFileSync(p, 'utf8') !== html).map(([p]) => p);
  const rel = (p) => p.slice(ROOT.length + 1);
  if (check) return { changed: changed.map(rel), stale: stale.map(rel) };
  for (const p of changed) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, pages[p]);
    log(`wrote ${rel(p)}`);
  }
  for (const p of stale) {
    rmSync(p);
    log(`removed ${rel(p)}`);
    try { rmdirSync(dirname(p)); } catch { /* the folder still holds other files, such as captions */ }
  }
  if (!changed.length && !stale.length) log('films pages are up to date');
  return { changed: changed.map(rel), stale: stale.map(rel) };
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const check = process.argv.includes('--check');
  try {
    const result = build({ check });
    if (check) {
      const out = [...result.changed, ...result.stale];
      if (out.length) {
        console.log(`out of date: ${out.join(', ')}\nrun: node scripts/build-films.mjs`);
        process.exit(1);
      }
      console.log('films pages are up to date');
    }
  } catch (e) {
    console.error(e.code === 'FILMS_CONFIG' ? e.message : e);
    process.exit(1);
  }
}
